def _calibration_scan(fp: str) -> bytes:
    """Свидетельство о поверке как картинка без текстового слоя — проверяет ветку OCR."""
    from PIL import Image, ImageDraw, ImageFont

    img = Image.new("L", (1600, 2000), 255)
    d = ImageDraw.Draw(img)
    f_big, f = ImageFont.truetype(fp, 56), ImageFont.truetype(fp, 40)
    y = 120
    for text, font in [("СВИДЕТЕЛЬСТВО О ПОВЕРКЕ", f_big), ("№ С-ТСТ/01-08-2026/000001", f),
                       ("Действительно до 01.07.2026", f), ("", f),
                       ("Средство измерений рефлектометр оптический", f), ("MTS-1000, № 12345-10", f),
                       ("наименование, тип", f), ("заводской номер 777001", f),
                       ("поверено в полном объёме", f), ("Поверитель Иванов И.И.", f)]:
        d.text((120, y), text, fill=0, font=font)
        y += 90
    out = io.BytesIO()
    img.save(out, format="PNG")
    return out.getvalue()


